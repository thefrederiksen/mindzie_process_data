#!/usr/bin/env python3
"""
SAP Accounts Payable Historical Dataset Upload

This script uploads the SAP AP historical dataset to Mindzie Studio for process mining analysis.
It uploads the year-to-date dataset with 1,500 completed cases for comprehensive analysis.

Requirements:
- Mindzie Studio API access
- Environment variables configured in .env file
- Historical dataset generated by historical_event_log.py
"""

import json
import requests
import os
from dotenv import load_dotenv
import pandas as pd
from datetime import datetime

# Load environment variables
load_dotenv()

# Mindzie Studio API Configuration
TENANT_ID = os.getenv('TENANT_ID')
PROJECT_ID = os.getenv('PROJECT_ID')
API_KEY = os.getenv('API_KEY')
API_BASE_URL = os.getenv('API_BASE_URL', 'https://www.mindziestudio.com')

def check_environment():
    """Check if required environment variables are set"""
    print("Checking environment configuration...")
    
    required_vars = ['TENANT_ID', 'PROJECT_ID', 'API_KEY']
    missing_vars = []
    
    for var in required_vars:
        if not os.getenv(var):
            missing_vars.append(var)
    
    if missing_vars:
        print(f"Error: Missing required environment variables: {missing_vars}")
        print("Please configure your .env file with the following variables:")
        print("  TENANT_ID=your_tenant_id_here")
        print("  PROJECT_ID=your_project_id_here")
        print("  API_KEY=your_api_key_here")
        return False
    
    print("Environment configuration OK ✓")
    return True

def check_dataset():
    """Check if the historical dataset exists"""
    print("Checking dataset availability...")
    
    csv_path = "output/sap_ap_year_to_date.csv"
    json_path = "output/sap_ap_year_to_date.json"
    
    if not os.path.exists(csv_path):
        print(f"Error: {csv_path} not found")
        print("Please run historical_event_log.py first to generate the dataset")
        return False
    
    if not os.path.exists(json_path):
        print(f"Error: {json_path} not found")
        print("Please run historical_event_log.py first to generate the dataset")
        return False
    
    # Load and validate dataset
    try:
        df = pd.read_csv(csv_path)
        with open(json_path, 'r') as f:
            data = json.load(f)
        
        print(f"Dataset found:")
        print(f"  CSV file: {csv_path} ({len(df)} events)")
        print(f"  JSON file: {json_path} ({len(data['events'])} events)")
        print(f"  Total cases: {len(data['case_metadata'])}")
        
        return True
        
    except Exception as e:
        print(f"Error loading dataset: {e}")
        return False

def upload_to_mindzie_studio():
    """Upload the historical dataset to Mindzie Studio"""
    print("Uploading to Mindzie Studio...")
    
    # API endpoint
    upload_url = f"{API_BASE_URL}/api/v1/tenants/{TENANT_ID}/projects/{PROJECT_ID}/datasets"
    
    # Headers
    headers = {
        'Authorization': f'Bearer {API_KEY}',
        'Content-Type': 'application/json'
    }
    
    # Load dataset
    csv_path = "output/sap_ap_year_to_date.csv"
    df = pd.read_csv(csv_path)
    
    # Prepare upload data
    upload_data = {
        "name": "SAP AP Historical Dataset",
        "description": "SAP Accounts Payable historical dataset with 1,500 completed invoice processing cases",
        "datasetType": "EVENT_LOG",
        "data": df.to_dict('records'),
        "metadata": {
            "source": "SAP ERP Accounts Payable",
            "timeRange": "2024-01-01 to 2025-05-04",
            "totalCases": len(df['CaseId'].unique()),
            "totalEvents": len(df),
            "activities": df['ActivityName'].unique().tolist(),
            "uploadedAt": datetime.now().isoformat()
        }
    }
    
    try:
        print(f"Uploading to: {upload_url}")
        response = requests.post(upload_url, headers=headers, json=upload_data)
        
        if response.status_code == 200 or response.status_code == 201:
            result = response.json()
            print("Upload successful! ✓")
            print(f"Dataset ID: {result.get('id', 'N/A')}")
            print(f"Status: {result.get('status', 'N/A')}")
            return True
        else:
            print(f"Upload failed with status code: {response.status_code}")
            print(f"Response: {response.text}")
            return False
            
    except Exception as e:
        print(f"Error during upload: {e}")
        return False

def main():
    """Main function to upload the historical dataset"""
    print("SAP Accounts Payable Historical Dataset Upload")
    print("="*50)
    
    # Check environment
    if not check_environment():
        return
    
    # Check dataset
    if not check_dataset():
        return
    
    # Upload to Mindzie Studio
    if upload_to_mindzie_studio():
        print("\nHistorical dataset upload completed successfully!")
        print("\nNext steps:")
        print("1. Log into your Mindzie Studio account")
        print("2. Navigate to your project")
        print("3. Find the 'SAP AP Historical Dataset' in your datasets")
        print("4. Start your process mining analysis")
    else:
        print("\nUpload failed. Please check your configuration and try again.")

if __name__ == "__main__":
    main() 